export const FLOOR_ORDER: FloorId[] = ['ground', 'first'];

/** Which floor a bundle location is drawn on, or null when it is not on the plan. */
export function floorOf(locationId: string): FloorId | null {
  for (const id of FLOOR_ORDER) {
    if (FLOORS[id].rooms.some((r) => r.id === locationId)) return id;
  }
  return null;
}

/** Position of a room's label anchor as a percentage of the floor's viewBox. */
export function anchorPercent(floor: Floor, room: FloorRoom): { x: number; y: number } {
  const [vx, vy, vw, vh] = floor.viewBox.split(' ').map(Number) as [number, number, number, number];
  return { x: ((room.cx - vx) / vw) * 100, y: ((room.cy - vy) / vh) * 100 };
}
